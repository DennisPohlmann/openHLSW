#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_is_sorted_and_unique() {
        for w in GAMES.windows(2) {
            assert!(
                w[0].name.to_lowercase() <= w[1].name.to_lowercase(),
                "{}",
                w[1].name
            );
        }
        let mut keys: Vec<_> = GAMES.iter().map(|g| g.key).collect();
        keys.sort();
        keys.dedup();
        assert_eq!(keys.len(), GAMES.len());
        assert!(by_key("ArmA").is_some_and(|g| g.not_detectable && g.supported()));
    }
}
