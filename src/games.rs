//! Games of HLSW's "IP/Port" list (from HLSW's Games.cfg). Most servers are detected
//! automatically (Source and Half-Life 1 answer A2S queries); games that cannot be detected
//! from the address alone have to be chosen in the list before adding the server.

/// How openHLSW queries servers of a game.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Protocol {
    /// Valve A2S (Source, Half-Life 1, CS2) – detected automatically.
    A2s,
    /// GameSpy 2 on a separate query port (ip:gameport:queryport).
    GameSpy2,
    /// A protocol openHLSW does not speak yet (Quake 3, GameSpy 1, Unreal, TeamSpeak, …).
    Unsupported,
}

#[derive(Debug)]
pub struct Game {
    /// HLSW's internal name (Games.cfg key).
    pub key: &'static str,
    pub name: &'static str,
    /// Key of the icon in assets/games ("" = none).
    pub icon: &'static str,
    /// Protocol name in HLSW (GS, Q3, HL2, …), shown for unsupported games.
    pub hlsw_protocol: &'static str,
    pub protocol: Protocol,
    /// Cannot be detected from the address: listed under "Not detectable games".
    pub not_detectable: bool,
    /// Query port used when the address has none (0 = must be given).
    pub default_query_port: u16,
}

impl Game {
    pub fn supported(&self) -> bool {
        self.protocol != Protocol::Unsupported
    }
}

