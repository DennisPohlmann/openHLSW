//! Games of the "IP/Port" list: HLSW's list (from its Games.cfg) and the games GameQ knows.
//! Most servers are detected automatically (Valve A2S, GameSpy 1 / 2); games that cannot be
//! detected from the address alone have to be chosen in the list before adding the server.

/// How openHLSW queries servers of a game (every protocol of HLSW's list).
pub use openhlsw::query::Protocol;

#[derive(Debug)]
pub struct Game {
    /// HLSW's internal name (Games.cfg key).
    pub key: &'static str,
    pub name: &'static str,
    /// Key of the icon in assets/games ("" = none).
    pub icon: &'static str,
    pub protocol: Protocol,
    /// Cannot be detected from the address: listed under "Not detectable games".
    pub not_detectable: bool,
    /// Query port used when the address has none (0 = see `port_diff`).
    pub default_query_port: u16,
    /// Query port = game port + this (Valve A2S of ARK, Squad …; GameSpy of SWAT 4 …).
    pub port_diff: i32,
    /// Game port used when the address has none (0 = 27015).
    pub default_port: u16,
}

impl Game {
    /// Query port for the game port `port`, when it differs from it.
    pub fn query_port(&self, port: u16) -> Option<u16> {
        if self.default_query_port > 0 {
            return Some(self.default_query_port);
        }
        if self.port_diff == 0 {
            return None;
        }
        u16::try_from(i32::from(port) + self.port_diff).ok()
    }
}

